// Writes ios/VirgaKit/Sources/VirgaPosting/Support/IDNATable.swift: what
// Node's URL parser (Ada) knows about each code point when it turns a host
// into ASCII, for VirgaPosting's WHATWG URL port (IDNA.swift).
//
//   node ios/scripts/generate-idna-table.mjs
//
// Everything is read from Node itself, through url.domainToASCII, so the
// Swift side holds Ada's own UTS #46 data rather than a reading of the
// standard: each code point's status and mapping (from its ASCII form when it
// follows an emoji, which nothing composes with or is refused beside), and,
// for each valid one, the properties Ada's validity check reads (its bidi
// class, its joining type and whether it is a virama), each found with a
// label that only that property decides. ios/parity/cases/posting-text.idna.js
// then holds the Swift port to Node character by character.
//
// Run it again when Node's URL parser moves to a newer Unicode.

import console from 'node:console';
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import { domainToASCII, domainToUnicode } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(
  here,
  '../VirgaKit/Sources/VirgaPosting/Support/IDNATable.swift',
);

const ok = (label) => domainToASCII(label) !== '';
const EMOJI = '\u{1F600}';
const ALEF = '\u05D0'; // Bidi R
const BEH = '\u0628'; // Bidi AL, joining type D
const ZWNJ = '\u200C';
const ZWJ = '\u200D';
const KA = '\u0915'; // a Devanagari letter, before a virama

const RANGES = [
  [0x80, 0xd7ff],
  [0xe000, 0x3ffff],
  [0xe0000, 0xe0fff],
];

/** The bidi class Ada's rule tells apart, for a valid code point. */
function bidiOf(c) {
  // An L character between two R ones breaks a right-to-left label.
  if (!ok(ALEF + c + ALEF)) return 'L';
  // An R, AL or AN character between two L ones breaks a left-to-right one.
  const rtl = !ok(`a${c}a`);
  // A right-to-left label may not hold both EN and AN.
  if (rtl && !ok(`${ALEF}${c}1`)) return 'A';
  if (rtl) return 'R';
  if (!ok(`${ALEF}${c}\u0661`)) return 'E';
  // Trailing NSM characters are passed over when the last one is checked.
  if (ok(ALEF + c)) return 'N';
  return 'O';
}

/**
 * Whether Ada refuses a label that starts with it (its list of combining
 * marks, which is older than Unicode's), tested after a letter its bidi class
 * lets stand beside it.
 */
function leadingMark(c, bidi) {
  return bidi === 'R' || bidi === 'A' ? !ok(c + ALEF) : !ok(`${c}a`);
}

/** The joining type Ada's ZWNJ rule reads, and whether it is a virama. */
function joinOf(c) {
  if (ok(KA + c + ZWJ)) return 'V';
  const before = ok(c + ZWNJ + BEH); // L or D
  const after = ok(BEH + ZWNJ + c); // R or D
  if (before && after) return 'D';
  if (before) return 'L';
  if (after) return 'R';
  return 'U';
}

const hex = (n) => n.toString(16).toUpperCase();
const entries = []; // [start, end, payload]
let mappedCount = 0;

function push(cp, payload) {
  const last = entries[entries.length - 1];
  if (last && last[1] === cp - 1 && last[2] === payload && payload[0] !== 'M')
    last[1] = cp;
  else entries.push([cp, cp, payload]);
}

for (const [from, to] of RANGES) {
  for (let cp = from; cp <= to; cp++) {
    const c = String.fromCodePoint(cp);
    if (cp === 0x200c || cp === 0x200d) {
      // The joiners: valid when nontransitional; their own rule decides.
      push(cp, 'VOU');
      continue;
    }
    const ascii = domainToASCII(EMOJI + c);
    if (!ascii) continue; // disallowed: the default
    const mapped = domainToUnicode(ascii).slice(EMOJI.length);
    if (mapped === c) {
      const bidi = bidiOf(c);
      push(cp, `V${bidi}${joinOf(c)}${leadingMark(c, bidi) ? 'M' : ''}`);
    } else if (mapped === '') {
      push(cp, 'I');
    } else {
      mappedCount++;
      push(cp, `M${[...mapped].map((ch) => hex(ch.codePointAt(0))).join(',')}`);
    }
  }
}

const lines = [];
let line = '';
for (const [start, end, payload] of entries) {
  const item = `${hex(start)}${end === start ? '' : `-${hex(end)}`}${payload[0] === 'M' ? '=' : ':'}${payload[0] === 'M' ? payload.slice(1) : payload}`;
  if (line.length + item.length > 96) {
    lines.push(line);
    line = '';
  }
  line += (line ? ';' : '') + item;
}
if (line) lines.push(line);

const swift = `// Generated by ios/scripts/generate-idna-table.mjs from Node ${process.version}'s
// URL parser (Ada ${process.versions.ada}): don't edit by hand, run the script.
//
// What Ada knows about each non-ASCII code point when it turns a host into
// ASCII. Each entry is \`start[-end]:Vbj[M]\` (valid, with its bidi class b:
// L, R or AL, A (AN), E (EN), N (NSM) or O (other); its joining type j:
// D, L, R, U, or V for a virama; and M when a label may not start with it),
// \`start[-end]:I\` (ignored: mapped to
// nothing) or \`code=target,…\` (mapped). Code points listed nowhere are
// disallowed. ${entries.length} entries, ${mappedCount} mapped.

extension IDNA {
  static let tableSource = """
${lines.join('\n')}
"""
}
`;
fs.writeFileSync(OUT, swift);
console.log(
  `${path.relative(process.cwd(), OUT)}: ${entries.length} entries, ${mappedCount} mapped, ${swift.length} bytes`,
);
