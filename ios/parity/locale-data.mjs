// Writes ios/VirgaKit/Sources/VirgaCore/Lib/LocaleData+Table.swift: the
// number, date and language data the Swift port of src/lib/locale.js formats
// with, read from this Node's Intl (cases/_localeData.js).
//
//   node ios/parity/locale-data.mjs
//
// Run it when `swift test` says the table and the core.localeData fixture
// disagree (after a Node upgrade brings new CLDR data), then commit both.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { localeTable } from './cases/_localeData.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const target = path.join(
  here,
  '../VirgaKit/Sources/VirgaCore/Lib/LocaleData+Table.swift',
);

const table = localeTable();
const json = JSON.stringify(table);
if (json.includes('"""#'))
  throw new Error('the table would end the raw string');

const swift = `// Ports src/lib/locale.js
//
// Generated by ios/parity/locale-data.mjs from Node's Intl (ICU ${table.runtime.icu},
// CLDR ${table.runtime.cldr}). Do not edit: run the script again. The
// core.localeData fixture holds this table to the runtime the web app's
// fixtures come from.

extension LocaleData {
  static let tableJSON = #"""
${json}
"""#
}
`;
fs.writeFileSync(target, swift);
console.log(
  `wrote ${path.relative(process.cwd(), target)} (${json.length} bytes of JSON)`,
);
