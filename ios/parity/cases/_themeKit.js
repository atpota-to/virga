// The kit's own measures: the sizes, weights, durations and the few
// colours that base.css, controls.css, app.css and theme.css's last rules
// give the controls, beside the tokens. Each is one declaration of one rule,
// named as the Swift side names it (VirgaCore/Theme/ThemeTokens+Kit.swift,
// `ThemeKit.<name>`), and read as `kind` says (_css.js, parseKitValue).
//
// ui.theme.js records each as the stylesheet has it, and
// ios/scripts/generate-theme-tokens.mjs writes the Swift constants from the
// same list, so a change to one of these declarations makes the fixture
// stale and the Swift test say which constant must follow. A rule that is
// renamed or loses the declaration throws while the fixture is written.
//
// These are the measures, not the components: how a button is laid out, a
// row's shape and what a control does are VirgaUI's (wave 4), from the same
// sheets; ios/DESIGN.md says what each is for.

