    '@😀.bsky.social',
    POST,
    AT_POST,
    LIST,
    'https://bsky.app/profile/a.b.c',
    'https://bsky.app/profile/did%3Aplc%3Aabc',
    'https://bsky.app/profile/50%off',
    'bsky.app/profile/jo.e...',
