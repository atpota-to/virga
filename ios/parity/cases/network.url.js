export default async function cases() {
  return [
    ...(await each(
      'parse',
      ABSOLUTE.map((input) => ({ input })),
      ({ input }) => parts(new URL(input)),
    )),
    ...(await each(
      'parseRelative',
      RELATIVE.map(([input, base]) => ({ input, base })),
      ({ input, base }) => parts(new URL(input, base)),
    )),
    ...(await each(
      'setSearch',
      [
        { url: 'https://virga.example/oauth/return', search: 'n=abc123' },
        { url: 'https://virga.example/oauth/return?old=1#f', search: '?n=a b' },
        { url: 'https://virga.example/p', search: '' },
        { url: 'https://virga.example/p?x', search: '?' },
        { url: 'https://virga.example/p', search: 'a=1#b' },
        { url: 'https://virga.example/p', search: 'q=\'"<>`' },
        { url: 'foo://h/p', search: "q='" },
        { url: 'https://virga.example/p', search: 'é=ü&😀' },
        { url: 'mailto:a@b', search: 'subject=x y' },
      ],
      ({ url, search }) => {
        const u = new URL(url);
        u.search = search;
        return parts(u);
      },
    )),
    ...(await each(
      'setSearchParam',
      [
        {
          url: 'https://s.example/api/oauth/login',
          name: 'handle',
          value: 'mira.example.com',
        },
        {
          url: 'https://s.example/api/oauth/login?handle=a&x=1&handle=b',
          name: 'handle',
          value: 'c d',
        },
        {
          url: 'https://s.example/api?a=b%20c&d=e+f',
          name: 'redirect_uri',
          value: 'https://v.example/oauth/return?n=1',
        },
        { url: 'https://s.example/api?#frag', name: 'k', value: '' },
        { url: 'https://s.example/api?%zz=%41', name: 'é', value: '😀&=+' },
        {
          url: 'https://s.example/api/oauth/upload-blob',
          name: 'encoding',
          value: 'image/png',
        },
      ],
      ({ url, name, value }) => {
        const u = new URL(url);
        u.searchParams.set(name, value);
        return parts(u);
      },
    )),
  ];
}
