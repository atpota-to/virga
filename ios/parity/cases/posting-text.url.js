export default async function cases() {
  const out = [];
  out.push(
    ...(await each(
      'parse',
      INPUTS.map((input) => ({ input })),
      ({ input }) => parts(new URL(input)),
    )),
  );
  out.push(
    ...(await each(
      'parseWithBase',
      RELATIVE.map(([input, base]) => ({ input, base })),
      ({ input, base }) => parts(new URL(input, base)),
    )),
  );
  out.push(
    ...(await each(
      'searchParams',
      QUERIES.map((query) => ({ query })),
      ({ query }) => {
        const params = new URLSearchParams(query);
        return { pairs: [...params], serialized: params.toString() };
      },
    )),
  );
  out.push(
    ...(await each(
      'searchParamsSet',
      [
        { query: 'a=1&b=2&a=3', name: 'a', value: 'x y' },
        { query: 'b=2', name: 'a', value: 'café/?&=' },
        { query: '', name: 'text', value: "I'm reading this \u{1F98B}" },
        { query: 'a=1', name: 'a', value: '' },
      ],
      ({ query, name, value }) => {
        const params = new URLSearchParams(query);
        params.set(name, value);
        return params.toString();
      },
    )),
  );
  out.push(
    ...(await each(
      'encodeURIComponent',
      COMPONENTS.map((text) => ({ text })),
      ({ text }) => encodeURIComponent(text),
    )),
  );
  out.push(
    ...(await each(
      'decodeURIComponent',
      DECODES.map((text) => ({ text })),
      ({ text }) => decodeURIComponent(text),
    )),
  );
  return out;
}
